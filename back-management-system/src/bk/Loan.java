package bk;

public class Loan {


	private int loan;
	private double loanId;
	private double restedAmount;
	private double requestedAmount;
	private double interestRate;
	private double savingAmount;
	
	public int getLoan() {
		return loan;
	}
	public void setLoan(int loan) {
		this.loan = loan;
	}
	public double getLoanId() {
		return loanId;
	}
	public void setLoanId(double loanId) {
		this.loanId = loanId;
	}
	public double getRestedAmount() {
		return restedAmount;
	}
	public void setRestedAmount(double restedAmount) {
		this.restedAmount = restedAmount;
	}
	public double getRequestedAmount() {
		return requestedAmount;
	}
	public void setRequestedAmount(double requestedAmount) {
		this.requestedAmount = requestedAmount;
	}
	public double getInterestRate() {
		return interestRate;
	}
	public void setInterestRate(double interestRate) {
		this.interestRate = interestRate;
	}
	public double getSavingAmount() {
		return savingAmount;
	}
	public void setSavingAmount(double savingAmount) {
		this.savingAmount = savingAmount;
	}

	// we need two methods getter and setter and they should be public
	

	
	

}
